#!/usr/bin/env python3
"""Builds HudIcons.js from the Icons8 SVGs here (see ../icons8.json) for the
volume and dictation HUDs: each icon's path, drawn in the color asked for.
Run it after changing an SVG: python3 plugins/macos-theme.osd/icons/make.py"""
import json, pathlib, re

here = pathlib.Path(__file__).parent
paths = {}
for svg in sorted(here.glob("*.svg")):
    text = svg.read_text()
    assert 'viewBox="0 0 50 50"' in text, svg
    paths[svg.stem] = re.findall(r' d="([^"]+)"', text)

js = '''// Generated by icons/make.py from the Icons8 SVGs in icons/; don't edit.
// The HUD icons as SVG data URLs in any color: Qt loads SVG from a data URL
// only in base64, and its Qt.btoa(string) is deprecated (the SVGs are ASCII).

var PATHS = %s

var B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
function base64(text) {
  var out = ""
  for (var i = 0; i < text.length; i += 3) {
    var a = text.charCodeAt(i), b = text.charCodeAt(i + 1), c = text.charCodeAt(i + 2)
    var n = (a << 16) | ((b || 0) << 8) | (c || 0)
    out += B64[(n >> 18) & 63] + B64[(n >> 12) & 63]
      + (i + 1 < text.length ? B64[(n >> 6) & 63] : "=") + (i + 2 < text.length ? B64[n & 63] : "=")
  }
  return out
}

// The icon called `name` in `color`, or "" for none of that name.
function icon(name, color) {
  var p = PATHS[name]
  if (!p) return ""
  var svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 50 50">'
    + p.map(function(d) { return '<path fill="' + color + '" d="' + d + '"/>' }).join("") + '</svg>'
  return "data:image/svg+xml;base64," + base64(svg)
}

if (typeof module !== "undefined") module.exports = { icon: icon, base64: base64, PATHS: PATHS }
''' % json.dumps(paths, indent=2)

for plugin in ("macos-theme.osd", "macos-theme.dictation-hud"):
    (here.parent.parent / plugin / "HudIcons.js").write_text(js)
print("HudIcons.js:", ", ".join(paths))
